#!/usr/bin/env node
/* ============================================================
   One-off: read each song's audio duration and PRINT the SQL to set
   songs.duration_seconds. It never writes to the database — you review the
   statements and run them through the admin/MCP path yourself.

   Durations feed the `duration` field of the MusicRecording JSON-LD added in
   1A-5. Without them the structured data simply omits duration, so this is a
   nice-to-have, not a blocker.

     npm i music-metadata        # not a repo dependency; install ad hoc
     node scripts/backfill-durations.mjs            # all songs missing one
     node scripts/backfill-durations.mjs --limit 5  # try a few first

   It reads audio_url straight from the committed songs.json and asks R2 for
   just the first slice of each file with a Range request, which is all a
   container header needs. Anything it cannot read is listed at the end so you
   know exactly what is left rather than being told it worked.

   From 1A-5 onwards the admin captures duration automatically when audio is
   attached, so this is only for the songs that predate that.
   ============================================================ */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const songs = JSON.parse(readFileSync(join(root, 'songs.json'), 'utf8'));

const limitArg = process.argv.indexOf('--limit');
const LIMIT = limitArg > -1 ? Number(process.argv[limitArg + 1]) || Infinity : Infinity;
const HEAD_BYTES = 512 * 1024;   // plenty for an MP3/MP4 header + duration atom

let parseBuffer;
try {
  ({ parseBuffer } = await import('music-metadata'));
} catch (e) {
  console.error('music-metadata is not installed. Run:  npm i music-metadata');
  console.error('(It is deliberately not a repo dependency — this is a one-off tool.)');
  process.exit(1);
}

const todo = songs.filter((s) => s.audio_url && s.duration_seconds == null).slice(0, LIMIT);
console.error(`[durations] ${todo.length} song(s) with audio and no duration.\n`);

const ok = [];
const failed = [];

for (const s of todo) {
  const label = s.title_translit || s.title || s.id;
  try {
    const res = await fetch(s.audio_url, { headers: { Range: `bytes=0-${HEAD_BYTES - 1}` } });
    if (!res.ok && res.status !== 206) throw new Error('HTTP ' + res.status);
    const buf = Buffer.from(await res.arrayBuffer());
    const mm = await parseBuffer(buf, { mimeType: res.headers.get('content-type') || undefined },
                                 { duration: true });
    const d = mm && mm.format && mm.format.duration;
    if (!d || !isFinite(d) || d <= 0) throw new Error('no duration in the header');
    ok.push({ id: s.id, label, secs: Math.round(d) });
    console.error(`  ok    ${label} — ${Math.round(d)}s`);
  } catch (e) {
    failed.push({ label, why: (e && e.message) || 'unknown' });
    console.error(`  skip  ${label} — ${(e && e.message) || 'unknown'}`);
  }
}

console.error(`\n[durations] read ${ok.length}, could not read ${failed.length}.`);
if (failed.length) {
  console.error('[durations] not read:');
  for (const f of failed) console.error(`  - ${f.label} (${f.why})`);
}

// Everything below is the reviewable output: SQL on stdout, notes on stderr,
// so `node scripts/backfill-durations.mjs > out.sql` gives a clean file.
if (ok.length) {
  console.log('-- Review, then run. Generated by scripts/backfill-durations.mjs');
  for (const r of ok) {
    console.log(`update public.songs set duration_seconds = ${r.secs} where id = '${r.id}';  -- ${r.label}`);
  }
} else {
  console.error('[durations] nothing to print.');
}
